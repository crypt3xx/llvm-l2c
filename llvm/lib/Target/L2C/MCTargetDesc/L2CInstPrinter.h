// L2CInstPrinter.h

#ifndef LLVM_LIB_TARGET_L2C_MCTARGETDESC_L2CINSTPRINTER_H
#define LLVM_LIB_TARGET_L2C_MCTARGETDESC_L2CINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class L2CInstPrinter : public MCInstPrinter {

public:
  L2CInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                 const MCRegisterInfo &MRI);

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  void printRegName(raw_ostream &O, MCRegister Reg) override;

  void printOperand(const MCInst *MI, unsigned OpNo, const MCSubtargetInfo &STI,
                    raw_ostream &O);
  void printBranchOperand(const MCInst *MI, uint64_t Address, unsigned OpNo,
                          const MCSubtargetInfo &STI, raw_ostream &O);

  void printCSRSystemRegister(const MCInst *MI, unsigned OpNo,
                              const MCSubtargetInfo &STI, raw_ostream &O);

  void printImm(const MCInst *MI, unsigned OpNo, const MCSubtargetInfo &STI,
                raw_ostream &O);

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address,
                        const MCSubtargetInfo &STI, raw_ostream &O);

  // Single argument version
  static const char *getRegisterName(MCRegister Reg);
  static const char *getRegisterName(MCRegister Reg, unsigned AltIdx);
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_L2C_MCTARGETDESC_L2CINSTPRINTER_H
