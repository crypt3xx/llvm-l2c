// Looks at a token type and creates the relevant operand from this
// information, adding to operands.
ParseStatus L2CAsmParser::parseOperand(OperandVector *Operands,
                                       StringRef Mnemonic) {

  auto Res = MatchOperandParserImpl(*Operands, Mnemonic);

  if (!Res.isNoMatch())
    return Res;

  // Attempt to parse token as register
  std::unique_ptr<L2COperand> Op = parseRegister();

  if (Op) {
    // We found a register
    Operands->push_back(std::move(Op));
    return ParseStatus::Success;
  }

  // If not register, attempt to parse token as immediate
  Op = parseImmediate();

  // If the token could not be parsed then fail
  if (!Op) {
    Error(Parser.getTok().getLoc(), "unknown operand");
    Parser.eatToEndOfStatement();
    return ParseStatus::Failure;
  }

  // We found an immediate
  Operands->push_back(std::move(Op));

  // Check if there's a "(" after the immediate
  if (Lexer.isNot(AsmToken::LParen))
    return ParseStatus::Success;

  // Left Parenthesis found, push the "(" token and consume it
  Operands->push_back(L2COperand::createToken("(", Lexer.getLoc()));
  Lex();

  Op = parseRegister();

  if (!Op) {
    Error(Parser.getTok().getLoc(), "expected register");
    Parser.eatToEndOfStatement();
    return ParseStatus::Failure;
  }

  // Found register after imm then "("
  Operands->push_back(std::move(Op));

  // We should find a ")" after the reg, else we fail
  if (Lexer.isNot(AsmToken::RParen)) {
    Error(Parser.getTok().getLoc(), "expected a )");
    Parser.eatToEndOfStatement();
    return ParseStatus::Failure;
  }

  // push the ")" token and consume it
  Operands->push_back(L2COperand::createToken(")", Lexer.getLoc()));
  Lex();

  return ParseStatus::Success;
}

std::unique_ptr<L2COperand> L2CAsmParser::parseRegister() {
  SMLoc StartLoc = Parser.getTok().getLoc();

  MCRegister Reg;

  if (Lexer.getKind() == AsmToken::Identifier) {
    Reg = MatchRegisterName(Lexer.getTok().getIdentifier());
    if (!Reg) {
      Reg = MatchRegisterAltName(Lexer.getTok().getIdentifier());
      if (!Reg)
        return nullptr;
    }
    SMLoc EndLoc = Lexer.getTok().getEndLoc();

    Parser.Lex(); // Eat identifier token

    return L2COperand::createReg(Reg, StartLoc, EndLoc);
  }

  return nullptr;
}

std::unique_ptr<L2COperand> L2CAsmParser::parseImmediate() {
  SMLoc StartLoc = Parser.getTok().getLoc();
  SMLoc EndLoc;

  const MCExpr *ExprVal;
  switch (Lexer.getKind()) {
  case AsmToken::Plus:
  case AsmToken::Minus:
  case AsmToken::Integer:
  case AsmToken::Dot: {
    if (!Parser.parseExpression(ExprVal, EndLoc))
      return L2COperand::createImm(ExprVal, StartLoc, EndLoc);
    [[fallthrough]];
  }
  default:
    return nullptr;
  }
}

bool L2CAsmParser::parseRegister(MCRegister &RegNum, SMLoc &StartLoc,
                                 SMLoc &EndLoc) {
  const AsmToken &Tok = getParser().getTok();
  StartLoc = Tok.getLoc();
  EndLoc = Tok.getEndLoc();
  std::unique_ptr<L2COperand> Op = parseRegister();
  if (Op != nullptr)
    RegNum = Op->getReg();
  return (Op == nullptr);
}

ParseStatus L2CAsmParser::tryParseRegister(MCRegister &Reg, SMLoc &StartLoc,
                                           SMLoc &EndLoc) {
  const AsmToken &Tok = getParser().getTok();
  StartLoc = Tok.getLoc();
  EndLoc = Tok.getEndLoc();
  std::unique_ptr<L2COperand> Op = parseRegister();
  if (Op == nullptr)
    return ParseStatus::NoMatch;
  Reg = Op->getReg();
  return ParseStatus::Success;
}

// Builds a CSR operand from an evaluated number, or returns nullptr if the
// number is out of range. Numbers and .set symbols never count as "written by
// name", so D6 (read-only check) does not apply to them.
static std::unique_ptr<L2COperand> createSysRegFromNumber(int64_t Imm, SMLoc S,
                                                          SMLoc E) {
  if (!isUInt<16>(Imm))
    return nullptr;

  StringRef Name; // only used for debug printing of the operand
  if (const L2CSysReg::SysReg *Reg = L2CSysReg::lookupSysRegByEncoding(Imm))
    Name = L2CSysReg::getSysRegStr(Reg->Name);

  return L2COperand::createSysReg(Name, S, E, Imm, /*ParsedFromName=*/false);
}

ParseStatus L2CAsmParser::parseCSRSystemRegister(OperandVector &Operands) {
  static constexpr const char *Msg =
      "operand must be a valid system register name or an integer in the "
      "range [0, 65535]";

  SMLoc S = getParser().getTok().getLoc();
  SMLoc E;

  switch (getLexer().getKind()) {
  default:
    // Not something a CSR operand can start with. The generic parser takes
    // over, and the matcher reports Msg through the DiagnosticString.
    return ParseStatus::NoMatch;

  case AsmToken::Identifier: {
    StringRef Name = getParser().getTok().getIdentifier();
    E = getParser().getTok().getEndLoc();

    // A CSR name. The generated lookup ignores case; D5 requires exact case.
    const L2CSysReg::SysReg *Reg = L2CSysReg::lookupSysRegByName(Name);
    if (Reg && L2CSysReg::getSysRegStr(Reg->Name) == Name) {
      Lex(); // consume the name
      Operands.push_back(L2COperand::createSysReg(Name, S, E, Reg->Encoding,
                                                  /*ParsedFromName=*/true));
      return ParseStatus::Success;
    }

    // Not a CSR name: try it as an expression, e.g. a .set symbol.
    [[fallthrough]];
  }
  case AsmToken::Integer:
  case AsmToken::Minus:
  case AsmToken::Plus:
  case AsmToken::LParen:
  case AsmToken::Tilde:
  case AsmToken::Exclaim: {
    const MCExpr *Res;
    if (getParser().parseExpression(Res, E))
      return ParseStatus::Failure;

    // Folds constants and symbols already defined with .set/.equ.
    int64_t Imm;
    if (Res->evaluateAsAbsolute(Imm))
      if (auto Op = createSysRegFromNumber(Imm, S, E)) {
        Operands.push_back(std::move(Op));
        return ParseStatus::Success;
      }

    return Error(S, Msg);
  }
  }
}

bool L2CAsmParser::parseInstruction(ParseInstructionInfo & /*Info*/,
                                    StringRef Name, SMLoc NameLoc,
                                    OperandVector &Operands) {
  StringRef Mnemonic = Name;

  // add mnemonic as the first operand
  Operands.push_back(L2COperand::createToken(Mnemonic, NameLoc));

  // If there are no more operands, then finish
  if (Lexer.is(AsmToken::EndOfStatement))
    return false;

  // Parse first operand
  if (!parseOperand(&Operands, Mnemonic).isSuccess())
    return true;

  // Parse until end of statement, consuming commas between operands
  while (Lexer.isNot(AsmToken::EndOfStatement) && Lexer.is(AsmToken::Comma)) {
    // Consume comma token
    Lex();

    // Parse next operand
    if (!parseOperand(&Operands, Mnemonic).isSuccess())
      return true;
  }

  // check we didn't consume the whole statement
  // if we didn't means we hit an unexpected token
  if (Lexer.isNot(AsmToken::EndOfStatement)) {
    Error(Parser.getTok().getLoc(), "unexpected token");
    Parser.eatToEndOfStatement();
    return true;
  }

  return false;
}

bool L2CAsmParser::matchAndEmitInstruction(SMLoc IdLoc, unsigned &Opcode,
                                           OperandVector &Operands,
                                           MCStreamer &Out, uint64_t &ErrorInfo,
                                           bool MatchingInlineAsm) {
  MCInst Inst;
  SMLoc ErrorLoc;

  auto Result =
      MatchInstructionImpl(Operands, Inst, ErrorInfo, MatchingInlineAsm);

  switch (Result) {
  case Match_Success: {
    // if it's a csrw instr, and if the sysreg was written by name, make sure
    // it's not read only
    if (Inst.getOpcode() == L2C::CSRW) {
      auto &Op = static_cast<L2COperand &>(*Operands[1]);
      if (Op.isSysReg() && Op.getSysReg().ParsedFromName) {
        const L2CSysReg::SysReg *Reg =
            L2CSysReg::lookupSysRegByEncoding(Op.getSysReg().Encoding);
        if (Reg && Reg->ReadOnly)
          return Error(Op.getStartLoc(),
                       "cannot write read-only CSR '" +
                           Twine(L2CSysReg::getSysRegStr(Reg->Name)) + "'");
      }
    }

    switch (Inst.getOpcode()) {
    case L2C::PseudoLI: {

      MCRegister Rd = Inst.getOperand(0).getReg();
      int64_t Imm = Inst.getOperand(1).getImm();

      int64_t V = SignExtend64<32>(Imm);

      if (isInt<16>(V)) {
        Out.emitInstruction(
            MCInstBuilder(L2C::ADDI).addReg(Rd).addReg(L2C::R0).addImm(V),
            getSTI());
        return false;
      }

      if (isUInt<16>(V)) {
        Out.emitInstruction(
            MCInstBuilder(L2C::ORI).addReg(Rd).addReg(L2C::R0).addImm(V),
            getSTI());
        return false;
      }

      int64_t Hi = (V >> 16) & 0xFFFF;
      int64_t Lo = V & 0xFFFF;
      Out.emitInstruction(MCInstBuilder(L2C::LUI).addReg(Rd).addImm(Hi),
                          getSTI());
      if (Lo != 0)
        Out.emitInstruction(
            MCInstBuilder(L2C::ORI).addReg(Rd).addReg(Rd).addImm(Lo), getSTI());

      return false;
    }
    case L2C::PseudoNOT: {

      MCRegister Rd = Inst.getOperand(0).getReg();
      MCRegister Rs = Inst.getOperand(1).getReg();

      Out.emitInstruction(
          MCInstBuilder(L2C::SUB).addReg(Rd).addReg(L2C::R0).addReg(Rs),
          getSTI());
      Out.emitInstruction(
          MCInstBuilder(L2C::ADDI).addReg(Rd).addReg(Rd).addImm(-1), getSTI());

      return false;
    }
    }

    Out.emitInstruction(Inst, getSTI());
    return false;
  }
  case Match_MissingFeature:
    return Error(IdLoc, "instruction use requires option to be enabled");

  case Match_MnemonicFail:
    return Error(IdLoc, "unrecognized instruction mnemonic");

  case Match_InvalidOperand: {
    ErrorLoc = IdLoc;
    if (ErrorInfo != ~0ULL) {
      if (ErrorInfo >= Operands.size())
        return Error(IdLoc, "too few operands for instruction");

      ErrorLoc = ((L2COperand &)*Operands[ErrorInfo]).getStartLoc();
      if (ErrorLoc == SMLoc())
        ErrorLoc = IdLoc;
    }
    return Error(ErrorLoc, "invalid operand for instruction");
  }

  default:
    break;
  }

  // Results generated from DiagnosticType in the .td files.
  if (Result >= FIRST_TARGET_MATCH_RESULT_TY) {
    ErrorLoc = IdLoc;
    if (ErrorInfo != ~0ULL) {
      if (ErrorInfo >= Operands.size())
        return Error(IdLoc, "too few operands for instruction");

      ErrorLoc = ((L2COperand &)*Operands[ErrorInfo]).getStartLoc();
      if (ErrorLoc == SMLoc())
        ErrorLoc = IdLoc;
    }
    if (const char *Msg = getMatchKindDiag((L2CMatchResultTy)Result))
      return Error(ErrorLoc, Msg);
    return Error(ErrorLoc, "invalid operand for instruction");
  }

  llvm_unreachable("Unknown match type detected!");
}

