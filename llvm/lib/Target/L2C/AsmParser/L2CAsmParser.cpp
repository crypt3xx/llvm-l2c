// Looks at a token type and creates the relevant operand from this
// information, adding to operands.
ParseStatus L2CAsmParser::parseOperand(OperandVector *Operands,
                                       StringRef Mnemonic) {

  // Attempt to parse token as register
  std::unique_ptr<L2COperand> Op = parseRegister();

  if (Op) {
    // We found a register
    Operands->push_back(std::move(Op));
    return ParseStatus::Success;
  }

  // If not register, attempt to parse token as immediate
  Op = parseImmediate();

  // If the token could not be parsed then fail
  if (!Op) {
    Error(Parser.getTok().getLoc(), "unknown operand");
    Parser.eatToEndOfStatement();
    return ParseStatus::Failure;
  }

  // We found an immediate
  Operands->push_back(std::move(Op));

  // Check if there's a "(" after the immediate
  if (Lexer.isNot(AsmToken::LParen))
    return ParseStatus::Success;

  // Left Parenthesis found, push the "(" token and consume it
  Operands->push_back(L2COperand::createToken("(", Lexer.getLoc()));
  Lex();

  Op = parseRegister();

  if (!Op) {
    Error(Parser.getTok().getLoc(), "expected register");
    Parser.eatToEndOfStatement();
    return ParseStatus::Failure;
  }

  // Found register after imm then "("
  Operands->push_back(std::move(Op));

  // We should find a ")" after the reg, else we fail
  if (Lexer.isNot(AsmToken::RParen)) {
    Error(Parser.getTok().getLoc(), "expected a )");
    Parser.eatToEndOfStatement();
    return ParseStatus::Failure;
  }

  // push the ")" token and consume it
  Operands->push_back(L2COperand::createToken(")", Lexer.getLoc()));
  Lex();

  return ParseStatus::Success;
}

std::unique_ptr<L2COperand> L2CAsmParser::parseRegister() {
  SMLoc StartLoc = Parser.getTok().getLoc();

  MCRegister Reg;

  if (Lexer.getKind() == AsmToken::Identifier) {
    Reg = MatchRegisterName(Lexer.getTok().getIdentifier());
    if (!Reg) {
      Reg = MatchRegisterAltName(Lexer.getTok().getIdentifier());
      if (!Reg)
        return nullptr;
    }
    SMLoc EndLoc = Lexer.getTok().getEndLoc();

    Parser.Lex(); // Eat identifier token

    return L2COperand::createReg(Reg, StartLoc, EndLoc);
  }

  return nullptr;
}

std::unique_ptr<L2COperand> L2CAsmParser::parseImmediate() {
  SMLoc StartLoc = Parser.getTok().getLoc();
  SMLoc EndLoc;

  const MCExpr *ExprVal;
  switch (Lexer.getKind()) {
  case AsmToken::Plus:
  case AsmToken::Minus:
  case AsmToken::Integer:
  case AsmToken::Dot: {
    if (!Parser.parseExpression(ExprVal, EndLoc))
      return L2COperand::createImm(ExprVal, StartLoc, EndLoc);
    [[fallthrough]];
  }
  default:
    return nullptr;
  }
}

bool L2CAsmParser::parseRegister(MCRegister &RegNum, SMLoc &StartLoc,
                                 SMLoc &EndLoc) {
  const AsmToken &Tok = getParser().getTok();
  StartLoc = Tok.getLoc();
  EndLoc = Tok.getEndLoc();
  std::unique_ptr<L2COperand> Op = parseRegister();
  if (Op != nullptr)
    RegNum = Op->getReg();
  return (Op == nullptr);
}

ParseStatus L2CAsmParser::tryParseRegister(MCRegister &Reg, SMLoc &StartLoc,
                                           SMLoc &EndLoc) {
  const AsmToken &Tok = getParser().getTok();
  StartLoc = Tok.getLoc();
  EndLoc = Tok.getEndLoc();
  std::unique_ptr<L2COperand> Op = parseRegister();
  if (Op == nullptr)
    return ParseStatus::NoMatch;
  Reg = Op->getReg();
  return ParseStatus::Success;
}

bool L2CAsmParser::parseInstruction(ParseInstructionInfo & /*Info*/,
                                    StringRef Name, SMLoc NameLoc,
                                    OperandVector &Operands) {
  StringRef Mnemonic = Name;

  // add mnemonic as the first operand
  Operands.push_back(L2COperand::createToken(Mnemonic, NameLoc));

  // If there are no more operands, then finish
  if (Lexer.is(AsmToken::EndOfStatement))
    return false;

  // Parse first operand
  if (!parseOperand(&Operands, Mnemonic).isSuccess())
    return true;

  // Parse until end of statement, consuming commas between operands
  while (Lexer.isNot(AsmToken::EndOfStatement) && Lexer.is(AsmToken::Comma)) {
    // Consume comma token
    Lex();

    // Parse next operand
    if (!parseOperand(&Operands, Mnemonic).isSuccess())
      return true;
  }

  // check we didn't consume the whole statement
  // if we didn't means we hit an unexpected token
  if (Lexer.isNot(AsmToken::EndOfStatement)) {
    Error(Parser.getTok().getLoc(), "unexpected token");
    Parser.eatToEndOfStatement();
    return true;
  }

  return false;
}

bool L2CAsmParser::matchAndEmitInstruction(SMLoc IdLoc, unsigned &Opcode,
                                           OperandVector &Operands,
                                           MCStreamer &Out, uint64_t &ErrorInfo,
                                           bool MatchingInlineAsm) {
  MCInst Inst;
  SMLoc ErrorLoc;

  auto Result =
      MatchInstructionImpl(Operands, Inst, ErrorInfo, MatchingInlineAsm);

  switch (Result) {
  case Match_Success:
    Out.emitInstruction(Inst, getSTI());
    Opcode = Inst.getOpcode();
    return false;
  case Match_MissingFeature:
    return Error(IdLoc, "instruction use requires option to be enabled");
  case Match_MnemonicFail:
    return Error(IdLoc, "unrecognized instruction mnemonic");
  case Match_InvalidOperand: {
    ErrorLoc = IdLoc;
    if (ErrorInfo != ~0ULL) {
      if (ErrorInfo >= Operands.size())
        return Error(IdLoc, "too few operands for instruction");

      ErrorLoc = ((L2COperand &)*Operands[ErrorInfo]).getStartLoc();
      if (ErrorLoc == SMLoc())
        ErrorLoc = IdLoc;
    }
    return Error(ErrorLoc, "invalid operand for instruction");
  }
  default:
    break;
  }

  // Results generated from DiagnosticType in the .td files.
  if (Result >= FIRST_TARGET_MATCH_RESULT_TY) {
    ErrorLoc = IdLoc;
    if (ErrorInfo != ~0ULL) {
      if (ErrorInfo >= Operands.size())
        return Error(IdLoc, "too few operands for instruction");

      ErrorLoc = ((L2COperand &)*Operands[ErrorInfo]).getStartLoc();
      if (ErrorLoc == SMLoc())
        ErrorLoc = IdLoc;
    }
    if (const char *Msg = getMatchKindDiag((L2CMatchResultTy)Result))
      return Error(ErrorLoc, Msg);
    return Error(ErrorLoc, "invalid operand for instruction");
  }

  llvm_unreachable("Unknown match type detected!");
}

